static int n_checks = 0;
static int n_failed = 0;
static int n_known = 0;   /* known issues in code outside steam_msgs, reported but not failed */

static void
check(gboolean ok, const char *what, int line)
{
	n_checks++;
	if (!ok) {
		n_failed++;
		fprintf(stderr, "FAIL line %d: %s\n", line, what);
	}
}

static void
check_eq(guint64 a, guint64 b, const char *what, int line)
{
	n_checks++;
	if (a != b) {
		n_failed++;
		fprintf(stderr, "FAIL line %d: %s: got %" G_GUINT64_FORMAT " (0x%" G_GINT64_MODIFIER "x), "
		        "expected %" G_GUINT64_FORMAT " (0x%" G_GINT64_MODIFIER "x)\n",
		        line, what, a, a, b, b);
	}
}

static void
check_str(const char *a, const char *b, const char *what, int line)
{
	n_checks++;
	if (a == NULL || b == NULL ? a != b : strcmp(a, b) != 0) {
		n_failed++;
		fprintf(stderr, "FAIL line %d: %s: got \"%s\", expected \"%s\"\n",
		        line, what, a ? a : "(null)", b ? b : "(null)");
	}
}

static void
check_bytes(const guint8 *a, gsize alen, const guint8 *b, gsize blen, const char *what, int line)
{
	n_checks++;
	if (alen != blen || (alen && memcmp(a, b, alen) != 0)) {
		gchar *ha = a ? steam_proto_hexdump(a, alen) : g_strdup("(null)");
		gchar *hb = b ? steam_proto_hexdump(b, blen) : g_strdup("(null)");
		n_failed++;
		fprintf(stderr, "FAIL line %d: %s:\n  got      %s\n  expected %s\n", line, what, ha, hb);
		g_free(ha);
		g_free(hb);
	}
}

#define CHECK(c)          check((c) ? TRUE : FALSE, #c, __LINE__)
#define CHECK_EQ(a, b)    check_eq((guint64)(a), (guint64)(b), #a, __LINE__)
#define CHECK_STR(a, b)   check_str((a), (b), #a, __LINE__)
/* Optional scalar present with value */
#define CHECK_HAS(m, f, v) G_STMT_START { \
	check((m)->has_##f, "has_" #f, __LINE__); \
	check_eq((guint64)(m)->f, (guint64)(v), #f, __LINE__); \
} G_STMT_END
#define CHECK_ABSENT(m, f) check(!(m)->has_##f, "!has_" #f, __LINE__)
#define CHECK_BA(ba, exp, exp_len) \
	check_bytes((ba) ? (ba)->data : NULL, (ba) ? (ba)->len : 0, (const guint8 *)(exp), (exp_len), #ba, __LINE__)

/* Hex string -> bytes (caller unrefs) */
static GByteArray *
unhex(const char *hex)
{
	GByteArray *b = g_byte_array_new();
	gsize i, n = strlen(hex);

	g_assert(n % 2 == 0);
	for (i = 0; i < n; i += 2) {
		guint8 v = (guint8)((g_ascii_xdigit_value(hex[i]) << 4) | g_ascii_xdigit_value(hex[i + 1]));
		g_byte_array_append(b, &v, 1);
	}
	return b;
}

static void
check_hex(const GByteArray *got, const char *expected_hex, const char *what, int line)
{
	GByteArray *exp = unhex(expected_hex);
	check_bytes(got->data, got->len, exp->data, exp->len, what, line);
	g_byte_array_unref(exp);
}
#define CHECK_HEX(ba, hex) check_hex((ba), (hex), "encode " #hex, __LINE__)

/* Encodes `m` with `fn` and compares with the vector. */
#define CHECK_ENCODE(fn, m, hex) G_STMT_START { \
	GByteArray *_o = g_byte_array_new(); \
	fn((m), _o); \
	check_hex(_o, (hex), "encode " #hex, __LINE__); \
	g_byte_array_unref(_o); \
} G_STMT_END

/* Decodes the vector into `m` (already initialised) and checks it succeeded. */
#define DECODE(fn, m, hex) G_STMT_START { \
	GByteArray *_i = unhex(hex); \
	check(fn((m), _i->data, _i->len), "decode " #hex, __LINE__); \
	g_byte_array_unref(_i); \
} G_STMT_END

/* Every decoder must reject a LEN field that runs past the end. */
static const guint8 malformed[] = { 0x0a, 0x05, 0xab };
#define CHECK_REJECTS(prefix, type) G_STMT_START { \
	type _m; \
	prefix##_init(&_m); \
	check(!prefix##_decode(&_m, malformed, sizeof(malformed)), "reject malformed " #prefix, __LINE__); \
	prefix##_clear(&_m); \
	prefix##_init(&_m); \
	check(prefix##_decode(&_m, NULL, 0), "accept empty " #prefix, __LINE__); \
	prefix##_clear(&_m); \
} G_STMT_END

