static GPtrArray *
new_packet_array(void)
{
	return g_ptr_array_new_with_free_func((GDestroyNotify)g_byte_array_unref);
}

/* Unpacks a Multi whose body/size are given and returns the packet count,
 * or -1 on failure. */
static int
try_unpack(const guint8 *body, gsize len, guint32 size_unzipped)
{
	SteamMsgMulti m;
	GPtrArray *pkts = new_packet_array();
	int ret;

	steam_msg_multi_init(&m);
	if (size_unzipped)
		STEAM_MSG_SET(&m, size_unzipped, size_unzipped);
	m.message_body = g_byte_array_new();
	g_byte_array_append(m.message_body, body, len);
	ret = steam_msg_multi_unpack(&m, pkts) ? (int)pkts->len : -1;
	if (ret < 0 && pkts->len != 0)
		ret = -2;  /* failure must not leave partial output */
	steam_msg_multi_clear(&m);
	g_ptr_array_unref(pkts);
	return ret;
}

static void
test_multi(void)
{
	SteamMsgMulti m;
	GPtrArray *pkts;
	GByteArray *payload, *gz;

	/* Uncompressed */
	steam_msg_multi_init(&m);
	DECODE(steam_msg_multi_decode, &m, VEC_MULTI_PLAIN);
	CHECK_ABSENT(&m, size_unzipped);
	CHECK(m.message_body != NULL);
	pkts = new_packet_array();
	CHECK(steam_msg_multi_unpack(&m, pkts));
	check_multi_packets(pkts);
	g_ptr_array_unref(pkts);
	CHECK_ENCODE(steam_msg_multi_encode, &m, VEC_MULTI_PLAIN);
	payload = g_byte_array_ref(m.message_body);
	steam_msg_multi_clear(&m);

	/* Gzip */
	steam_msg_multi_init(&m);
	DECODE(steam_msg_multi_decode, &m, VEC_MULTI_GZIP);
	CHECK_HAS(&m, size_unzipped, payload->len);
	pkts = new_packet_array();
	CHECK(steam_msg_multi_unpack(&m, pkts));
	check_multi_packets(pkts);
	g_ptr_array_unref(pkts);
	CHECK_ENCODE(steam_msg_multi_encode, &m, VEC_MULTI_GZIP);
	gz = g_byte_array_ref(m.message_body);
	steam_msg_multi_clear(&m);

	/* Hand-built Multi encodes like the vector */
	steam_msg_multi_init(&m);
	STEAM_MSG_SET(&m, size_unzipped, payload->len);
	m.message_body = g_byte_array_ref(gz);
	CHECK_ENCODE(steam_msg_multi_encode, &m, VEC_MULTI_GZIP);
	steam_msg_multi_clear(&m);

	CHECK_EQ(try_unpack(payload->data, payload->len, 0), 3);
	CHECK_EQ(try_unpack(gz->data, gz->len, payload->len), 3);
	/* wrong size_unzipped either way */
	CHECK_EQ(try_unpack(gz->data, gz->len, payload->len + 1), -1);
	CHECK_EQ(try_unpack(gz->data, gz->len, payload->len - 1), -1);
	/* truncated gzip */
	CHECK_EQ(try_unpack(gz->data, gz->len - 10, payload->len), -1);
	/* corrupted deflate data / CRC */
	{
		GByteArray *bad = g_byte_array_new();
		g_byte_array_append(bad, gz->data, gz->len);
		bad->data[bad->len - 6] ^= 0xff;  /* inside the CRC32 trailer */
		CHECK_EQ(try_unpack(bad->data, bad->len, payload->len), -1);
		g_byte_array_unref(bad);
	}
	/* not compressed at all but size_unzipped set */
	CHECK_EQ(try_unpack(payload->data, payload->len, payload->len), -1);
	/* framing errors: trailing partial length, length past end */
	{
		GByteArray *bad = g_byte_array_new();
		g_byte_array_append(bad, payload->data, payload->len);
		g_byte_array_append(bad, (const guint8 *)"\x01\x00", 2);
		CHECK_EQ(try_unpack(bad->data, bad->len, 0), -1);
		g_byte_array_set_size(bad, payload->len);
		g_byte_array_append(bad, (const guint8 *)"\x05\x00\x00\x00\x01", 5);
		CHECK_EQ(try_unpack(bad->data, bad->len, 0), -1);
		g_byte_array_unref(bad);
	}
	/* zero-length packet entry is framed correctly (yields an empty packet) */
	CHECK_EQ(try_unpack((const guint8 *)"\x00\x00\x00\x00", 4, 0), 1);
	/* empty Multi */
	CHECK_EQ(try_unpack(NULL, 0, 0), 0);
	steam_msg_multi_init(&m);
	pkts = new_packet_array();
	CHECK(steam_msg_multi_unpack(&m, pkts));
	CHECK_EQ(pkts->len, 0);
	STEAM_MSG_SET(&m, size_unzipped, 10);  /* compressed but no body */
	CHECK(!steam_msg_multi_unpack(&m, pkts));
	g_ptr_array_unref(pkts);
	steam_msg_multi_clear(&m);

	/* zlib-wrapped (not gzip) data is accepted too */
	{
		uLongf zlen = compressBound(payload->len);
		guint8 *z = g_malloc(zlen);
		CHECK(compress2(z, &zlen, payload->data, payload->len, 9) == Z_OK);
		CHECK_EQ(try_unpack(z, zlen, payload->len), 3);
		g_free(z);
	}

	/* A failing unpack leaves previously collected packets alone */
	{
		SteamMsgMulti a;
		pkts = new_packet_array();
		steam_msg_multi_init(&a);
		a.message_body = g_byte_array_ref(payload);
		CHECK(steam_msg_multi_unpack(&a, pkts));
		STEAM_MSG_SET(&a, size_unzipped, 5);
		CHECK(!steam_msg_multi_unpack(&a, pkts));
		CHECK_EQ(pkts->len, 3);
		steam_msg_multi_clear(&a);
		g_ptr_array_unref(pkts);
	}

	g_byte_array_unref(payload);
	g_byte_array_unref(gz);
	CHECK_REJECTS(steam_msg_multi, SteamMsgMulti);
}

