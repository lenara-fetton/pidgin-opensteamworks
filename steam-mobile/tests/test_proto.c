	CHECK_STR(steam_emsg_to_string(STEAM_EMSG_CLIENT_LOGON), "ClientLogon");
	CHECK_STR(steam_emsg_to_string(1), "Multi");
	CHECK_STR(steam_emsg_to_string(9805), "ClientHello");
