static void
test_packets(void)
{
	GByteArray *pkt = unhex(VEC_PACKET_LOGON);
	GByteArray *logon = unhex(VEC_LOGON);
	GByteArray *out;
	SteamMsgProtoBufHeader h;
	const guint8 *body;
	gsize body_len;
	guint32 emsg = 0;
	gsize n;

	CHECK(steam_msg_packet_parse(pkt->data, pkt->len, &emsg, &h, &body, &body_len));
	CHECK_EQ(emsg, STEAM_EMSG_CLIENT_LOGON);
	CHECK_EQ(emsg, 5514);
	CHECK_HAS(&h, steamid, SID0);
	CHECK_HAS(&h, client_sessionid, 0);
	check_bytes(body, body_len, logon->data, logon->len, "logon body", __LINE__);

	out = g_byte_array_new();
	steam_msg_packet_build(STEAM_EMSG_CLIENT_LOGON, &h, logon, out);
	CHECK_HEX(out, VEC_PACKET_LOGON);
	g_byte_array_unref(out);
	steam_msg_protobuf_header_clear(&h);

	/* Every truncation of the header region fails; a truncated body is
	 * not detectable at this layer and is left to the body decoder */
	for (n = 0; n < 8 + 11; n++) {
		gboolean ok = steam_msg_packet_parse(pkt->data, n, &emsg, &h, &body, &body_len);
		check(!ok, "truncated packet rejected", __LINE__);
		steam_msg_protobuf_header_clear(&h);
	}
	CHECK(steam_msg_packet_parse(pkt->data, 8 + 11, &emsg, &h, &body, &body_len));
	CHECK_EQ(body_len, 0);
	steam_msg_protobuf_header_clear(&h);

	/* Non-protobuf packet: rejected, but EMsg reported */
	{
		guint8 raw[8] = { 0x8a, 0x15, 0, 0, 0, 0, 0, 0 };
		emsg = 0;
		CHECK(!steam_msg_packet_parse(raw, sizeof(raw), &emsg, &h, NULL, NULL));
		CHECK_EQ(emsg, 5514);
		steam_msg_protobuf_header_clear(&h);
	}
	/* Header length larger than the packet */
	{
		guint8 raw[9] = { 0x01, 0, 0, 0x80, 0x02, 0, 0, 0, 0x08 };
		CHECK(!steam_msg_packet_parse(raw, sizeof(raw), &emsg, &h, NULL, NULL));
		steam_msg_protobuf_header_clear(&h);
	}
	/* Header length 0xffffffff must not overflow */
	{
		guint8 raw[8] = { 0x01, 0, 0, 0x80, 0xff, 0xff, 0xff, 0xff };
		CHECK(!steam_msg_packet_parse(raw, sizeof(raw), &emsg, &h, NULL, NULL));
		steam_msg_protobuf_header_clear(&h);
	}
	/* Malformed header */
	{
		guint8 raw[11] = { 0x01, 0, 0, 0x80, 0x03, 0, 0, 0, 0x0a, 0x05, 0xab };
		CHECK(!steam_msg_packet_parse(raw, sizeof(raw), &emsg, &h, NULL, NULL));
		steam_msg_protobuf_header_clear(&h);
	}
	CHECK(!steam_msg_packet_parse(NULL, 0, &emsg, &h, NULL, NULL));
	steam_msg_protobuf_header_clear(&h);

	/* Empty header and body */
	out = g_byte_array_new();
	steam_msg_packet_build(STEAM_EMSG_CLIENT_LOG_OFF, NULL, NULL, out);
	CHECK_HEX(out, "c2020080" "00000000");
	CHECK(steam_msg_packet_parse(out->data, out->len, &emsg, &h, &body, &body_len));
	CHECK_EQ(emsg, STEAM_EMSG_CLIENT_LOG_OFF);
	CHECK_EQ(body_len, 0);
	CHECK_ABSENT(&h, steamid);
	steam_msg_protobuf_header_clear(&h);
	g_byte_array_unref(out);

	/* ServiceMethod notification packet, then its body */
	{
		GByteArray *p = unhex(VEC_PACKET_SERVICE_METHOD);
		SteamMsgFriendMessagesIncomingMessage im;

		CHECK(steam_msg_packet_parse(p->data, p->len, &emsg, &h, &body, &body_len));
		CHECK_EQ(emsg, STEAM_EMSG_SERVICE_METHOD);
		CHECK_STR(h.target_job_name, STEAM_NOTIFY_FRIEND_MESSAGES_INCOMING_MESSAGE);
		CHECK_HAS(&h, jobid_target, G_GUINT64_CONSTANT(0x1122334455667788));
		CHECK_ABSENT(&h, jobid_source);
		steam_msg_friend_messages_incoming_message_init(&im);
		CHECK(steam_msg_friend_messages_incoming_message_decode(&im, body, body_len));
		CHECK_HAS(&im, steamid_friend, SID2);
		CHECK_HAS(&im, chat_entry_type, 2);
		steam_msg_friend_messages_incoming_message_clear(&im);
		steam_msg_protobuf_header_clear(&h);

		/* rebuild it */
		steam_msg_protobuf_header_init(&h);
		STEAM_MSG_SET(&h, jobid_target, G_GUINT64_CONSTANT(0x1122334455667788));
		h.target_job_name = g_strdup(STEAM_NOTIFY_FRIEND_MESSAGES_INCOMING_MESSAGE);
		steam_msg_friend_messages_incoming_message_init(&im);
		STEAM_MSG_SET(&im, steamid_friend, SID2);
		STEAM_MSG_SET(&im, chat_entry_type, 2);
		STEAM_MSG_SET(&im, rtime32_server_timestamp, 1700000124);
		{
			GByteArray *b = g_byte_array_new();
			out = g_byte_array_new();
			steam_msg_friend_messages_incoming_message_encode(&im, b);
			steam_msg_packet_build(STEAM_EMSG_SERVICE_METHOD, &h, b, out);
			CHECK_HEX(out, VEC_PACKET_SERVICE_METHOD);
			g_byte_array_unref(out);
			g_byte_array_unref(b);
		}
		steam_msg_friend_messages_incoming_message_clear(&im);
		steam_msg_protobuf_header_clear(&h);
		g_byte_array_unref(p);
	}

	g_byte_array_unref(pkt);
	g_byte_array_unref(logon);
}

