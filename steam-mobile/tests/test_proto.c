static void
test_proto_varints(void)
{
	static const guint64 values[] = {
		0, 1, 127, 128, 300, 16383, 16384, 2097151, 2097152,
		G_MAXUINT32, G_GUINT64_CONSTANT(0x100000000),
		G_GUINT64_CONSTANT(0x7fffffffffffffff), G_GUINT64_CONSTANT(0x8000000000000000),
		G_MAXUINT64
	};
	static const guint lengths[] = { 1, 1, 1, 2, 2, 2, 3, 3, 4, 5, 5, 9, 10, 10 };
	guint i;

	for (i = 0; i < G_N_ELEMENTS(values); i++) {
		GByteArray *b = g_byte_array_new();
		SteamProtoReader r;

		steam_proto_put_varint(b, 1, values[i]);
		CHECK_EQ(b->len, 1 + lengths[i]);
		steam_proto_reader_init(&r, b->data, b->len);
		CHECK(steam_proto_next(&r));
		CHECK_EQ(r.field, 1);
		CHECK_EQ(r.wt, STEAM_PROTO_WT_VARINT);
		CHECK_EQ(r.varint, values[i]);
		CHECK(!steam_proto_next(&r));
		CHECK(!r.error);
		g_byte_array_unref(b);
	}

	{
		GByteArray *b = g_byte_array_new();
		steam_proto_put_varint(b, 1, 300);
		CHECK_HEX(b, "08ac02");
		g_byte_array_unref(b);
	}
}

static void
test_proto_int32(void)
{
	static const gint32 values[] = { 0, 1, -1, 150, -150, G_MAXINT32, G_MININT32, -203 };
	guint i;
	GByteArray *b;

	for (i = 0; i < G_N_ELEMENTS(values); i++) {
		SteamProtoReader r;

		b = g_byte_array_new();
		steam_proto_put_int32(b, 2, values[i]);
		/* negative int32 is sign extended to 10 bytes */
		CHECK_EQ(b->len, values[i] < 0 ? 11 : b->len);
		steam_proto_reader_init(&r, b->data, b->len);
		CHECK(steam_proto_next(&r));
		CHECK_EQ(r.field, 2);
		CHECK_EQ(steam_proto_int32(&r), values[i]);
		g_byte_array_unref(b);
	}

	b = g_byte_array_new();
	steam_proto_put_int32(b, 1, -1);
	CHECK_HEX(b, "08ffffffffffffffffff01");
	g_byte_array_unref(b);

	/* A 5-byte (uint32-style) negative encoding must also decode */
	{
		static const guint8 in[] = { 0x08, 0xff, 0xff, 0xff, 0xff, 0x0f };
		SteamProtoReader r;
		steam_proto_reader_init(&r, in, sizeof(in));
		CHECK(steam_proto_next(&r));
		CHECK_EQ(steam_proto_int32(&r), -1);
		CHECK_EQ(steam_proto_uint32(&r), G_MAXUINT32);
	}
}

