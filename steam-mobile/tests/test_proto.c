	CHECK_EQ(h.jobid_target, STEAM_JOBID_NONE);
	CHECK(h.target_job_name == NULL);
	CHECK_ABSENT(&h, eresult);
	CHECK_EQ(h.eresult, 2);
	CHECK(h.error_message == NULL);
	CHECK_ABSENT(&h, realm);
	CHECK_ENCODE(steam_msg_protobuf_header_encode, &h, VEC_HEADER_LOGON);

	DECODE(steam_msg_protobuf_header_decode, &h, VEC_HEADER_EXTRA);
